import fs from 'node:fs/promises';
import vm from 'node:vm';
const read=async path=>fs.readFile(new URL('../'+path,import.meta.url),'utf8');
const [batch,app,version,sw]=await Promise.all(['engine/r18-batch.js','app.js','VERSION','sw.js'].map(read));
const ok=(condition,msg)=>{if(!condition)throw Error(msg)};
for(const [name,src] of [['r18-batch.js',batch],['app.js',app],['sw.js',sw]]){try{new Function(src)}catch(e){throw Error(name+': '+e.message)}}
const release=Number(version.trim().split('-r').at(-1));ok(release>=63&&app.includes(`APP_VERSION='${version.trim()}'`)&&sw.includes(`CACHE='yt3-v20261023-${release}'`),'R63+ release/cache mismatch');
ok(batch.includes("tentativeCandidate(r.candidates,state.players,r.category||'')"),'Screenshot header not provided for candidate confidence');
ok(batch.includes('categoryMatches')&&batch.includes('original||screenSupported||obviousFirst'),'Distinct evidence-based inference paths missing');
ok(!batch.includes('window.renderBatchGroup=')&&!batch.includes('fetch('),'Do not force columns or invoke cloud recognition');
const context={window:{},document:{getElementById:()=>({})}};
vm.runInNewContext(batch,context,{timeout:1500});
const infer=context.window.yt3TentativeCandidate,reconcile=context.window.yt3ReconcileRowCrops;
const pitcher={_uid:'p','名前':'山田 太郎',_position:'投手'};
const catcher={_uid:'c','名前':'森本 健太',_position:'捕手'};
const other={_uid:'o','名前':'山田 次郎',_position:'投手'};
const dup={_uid:'z','名前':'山田 太郎',_position:'投手'};
const roster=[pitcher,catcher,other];
const cand=(p,score,visualScore=score)=>({p,score,visualScore});
const candidates=(a,b)=>[a,b];
ok(infer(candidates(cand(pitcher,.56,.53),cand(other,.50,.51)),roster)===null,'No extra confidence without screenshot evidence');
ok(infer(candidates(cand(pitcher,.56,.53),cand(other,.50,.51)),roster,'投手')?.p?._uid==='p','Aligned position header should enable moderate estimate');
ok(infer(candidates(cand(pitcher,.66,.60),cand(other,.62,.61)),roster)?.p?._uid==='p','Clear visual first choice should become an estimate');
ok(infer(candidates(cand(pitcher,.56,.53),cand(catcher,.50,.51)),roster,'捕手')===null,'Conflicting screenshot position must block automatic inference');
ok(infer(candidates(cand(pitcher,.54,.53),cand(other,.49,.48)),roster,'投手')===null,'Too low top score must remain candidate');
ok(infer(candidates(cand(pitcher,.61,.56),cand(other,.60,.54)),roster,'投手')===null,'Near tie must stay a candidate');
ok(infer(candidates(cand(pitcher,.62,.57),cand(other,.54,.53)),[...roster,dup],'投手')===null,'Duplicate Japanese name must not be promoted');
ok(infer(candidates(cand(pitcher,.62,.57),cand(other,.54,.53)),roster,'投手')?.p?._uid==='p','Previously inferred result must remain inferred');
const C=(top,score,margin,match=null)=>({canvas:{},score,m:{match,candidates:[cand(top,score),cand(other,score-margin)],margin}});
const independent=reconcile(C(pitcher,.68,.11),C(pitcher,.675,.105),roster);
ok(independent.m.match?.p?._uid==='p','Independent aligned and original crops can confirm with safe corroboration');
const poor=reconcile(C(pitcher,.66,.095),C(pitcher,.658,.095),roster);
ok(!poor.m.match,'Weak duplicate crops must not confirm');
const disagreement=reconcile(C(pitcher,.68,.11),C(catcher,.68,.11),roster);
ok(!disagreement.m.match,'Conflicting independent crops must not confirm');
console.log('R63: source-independent higher estimate coverage, strict same-name/position/margin guards, narrowly adjusted two-crop confirmation, no AI.');
