ok(a.rows.find(x=>x[1].includes('20523554'))[2].includes('未實測'),'Unsupported signing bonus code');
ok(a.rows.find(x=>x[1].includes('203F8B80'))[2].includes('衰退'),'Age display hazard missing');
const src=sources.find(x=>x.url==='https://forum.gamer.com.tw/C.php?bsn=6035&snA=214&tnum=1');
